def display_scores(scores):
    print("\n=== Student Scores ===")
    for index, score in enumerate(scores):
        print(f"{index}: {score}")


def search_score(scores):
    try:
        target = int(input("Enter the score to search for: "))
    except ValueError:
        print("Please enter a whole number.")
        return

    matches = [index for index, score in enumerate(scores) if score == target]
    if matches:
        print(f"Score {target} found at index/indices: {', '.join(map(str, matches))}")
    else:
        print(f"Score {target} was not found.")


def compute_average(scores):
    if scores:
        print(f"Average score: {sum(scores) / len(scores):.2f}")
    else:
        print("There are no scores to average.")


def update_score(scores):
    display_scores(scores)

    try:
        index = int(input("Enter the index of the score to update: "))
        new_score = int(input("Enter the new score: "))
    except ValueError:
        print("Please enter whole numbers.")
        return

    if 0 <= index < len(scores):
        scores[index] = new_score
        print("Score updated.")
        display_scores(scores)
    else:
        print("That index is out of range.")


def main():
    scores = [85, 92, 78, 90, 88]

    while True:
        print("\n=== Student Score Analyzer ===")
        print("\nSelect the number of the operation you want to perform:")
        print("\n1. Display Scores")
        print("2. Search Score")
        print("3. Compute Average Score")
        print("4. Update Score")
        print("5. Display Updated Scores")
        print("6. Exit")

        choice = input("Enter your choice: ")

        if choice == "1":
            display_scores(scores)
        elif choice == "2":
            search_score(scores)
        elif choice == "3":
            compute_average(scores)
        elif choice == "4":
            update_score(scores)
        elif choice == "5":
            display_scores(scores)
        elif choice == "6":
            print("Goodbye!")
            break
        else:
            print("Invalid choice. Please select a number from 1 to 6.")


if __name__ == "__main__":
    main()